#!/usr/bin/env bash
set -euo pipefail
ROOT="${1:-$(cd "$(dirname "$0")/.." && pwd)}"
[[ "$(tr -d '\r\n' < "$ROOT/VERSION")" =~ ^5\.0\.0-dev\.6\.(8[4-9]|90)$ || "$(tr -d '\r\n' < "$ROOT/VERSION")" == "5.0.0-dev.7.0" ]]
API="$ROOT/panel/public/api.php"; ADMIN="$ROOT/panel/public/admin.php"; JS="$ROOT/panel/public/assets/app.js"; CUST="$ROOT/panel/public/assets/customer.js"; MAIL="$ROOT/agent/internal/hostadapter/mail_secure.go"; SERVER="$ROOT/agent/internal/api/server_platform.go"; INSTALL="$ROOT/install/privora-install.sh"
grep -Fq "['automatic','detected','discovered']" "$API"
grep -Fq "Hosting package policy is unavailable for this account" "$API"
grep -Fq 'id="mailDomainOwner"' "$ADMIN"
grep -Fq 'Hosting account (owner)' "$ADMIN"
grep -Fq 'function populateMailOwners' "$JS"
grep -Fq 'syncMailDomainOwner' "$JS"
grep -Fq 'Selected hosting account does not own this domain' "$API"
! grep -Fq 'Outbound/hour' "$ADMIN"
! grep -Fq 'Outbound messages/hour' "$ROOT/panel/public/customer.php"
grep -Fq 'ConfigureMailDomain' "$SERVER"
grep -Fq 'ProvisionMailAlias' "$SERVER"
grep -Fq '"simulation": false' "$SERVER"
grep -Fq 'disable_plaintext_auth = yes' "$MAIL"
grep -Fq 'port = 993' "$MAIL"
grep -Fq 'port = 995' "$MAIL"
grep -Fq 'port = 0' "$MAIL"
grep -Fq 'submission/inet' "$MAIL"
grep -Fq 'submissions/inet' "$MAIL"
grep -Fq 'smtpd_tls_wrappermode=yes' "$MAIL"
grep -Fq 'tls_server_sni_maps' "$MAIL"
grep -Fq 'mail._domainkey' "$MAIL"
grep -Fq 'virtual_aliases' "$MAIL"
grep -Fq 'dovecot-pop3d' "$INSTALL"
grep -Fq 'mail_ports=", 25, 465, 587, 993, 995"' "$INSTALL"
! grep -Fq "['quota_mb','outbound_limit_per_hour']" "$CUST"
echo 'PASS: 6.84 legacy package reconciliation + secure mail + owner dropdown contract'
